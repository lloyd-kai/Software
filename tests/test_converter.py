"""核心算法测试：数字文本 -> 中文读法。

运行：pytest（在项目根目录，无需先安装包，pythonpath 已指向 src）
"""

import pytest

from number2speech.converter import (
    digits_to_chinese,
    four_digits_to_chinese,
    integer_to_chinese,
    num_to_chinese,
)


# ---------------------------------------------------------------------------
# 4 位以内：零的两条规则
# ---------------------------------------------------------------------------
@pytest.mark.parametrize("seg, expect", [
    ("2382", "二千三百八十二"),
    ("7", "七"),
    ("20", "二十"),               # 末尾零不读
    ("1005", "一千零五"),          # 连续零只读一个
    ("1010", "一千零一十"),
    ("9999", "九千九百九十九"),
    ("0005", "五"),               # 开头的零不补
])
def test_four_digits(seg, expect):
    assert four_digits_to_chinese(seg) == expect


# ---------------------------------------------------------------------------
# 万 / 亿分组
# ---------------------------------------------------------------------------
@pytest.mark.parametrize("s, expect", [
    ("0", "零"),
    ("000", "零"),
    ("10", "十"),                 # 一十 -> 十
    ("12", "十二"),
    ("110", "一百一十"),
    ("10000", "一万"),             # 末尾空组不补零
    ("10005", "一万零五"),          # 组间补零
    ("100000001", "一亿零一"),      # 跨大单位补零
    ("1234567890", "十二亿三千四百五十六万七千八百九十"),
    ("2147483647", "二十一亿四千七百四十八万三千六百四十七"),  # int 上限恰好通过
])
def test_integer(s, expect):
    assert integer_to_chinese(s) == expect


# ---------------------------------------------------------------------------
# 自然读法入口：正负号、小数点、脏输入
# ---------------------------------------------------------------------------
@pytest.mark.parametrize("text, expect", [
    ("2382", "二千三百八十二"),
    ("-12.5", "负十二点五"),
    ("负12.5", "负十二点五"),
    ("0.07", "零点零七"),
    ("  12 ", "十二"),             # 前后空白被清理
    ("12ab", "十二"),              # 非数字字符被忽略
    ("abc", ""),                   # 没有任何数字 -> 空串
    ("", ""),
    ("   ", ""),
    ("2147483647", "二十一亿四千七百四十八万三千六百四十七"),  # int 上限边界
])
def test_num_to_chinese(text, expect):
    assert num_to_chinese(text) == expect


@pytest.mark.parametrize("text", [
    "2147483648",                 # 刚超过 int 上限
    "99999999999",                # 远超 int 上限
    "12345678901234567",          # 17 位：直接拒绝，不再逐位读
])
def test_num_to_chinese_over_int_limit(text):
    with pytest.raises(ValueError):
        num_to_chinese(text)


def test_none_input():
    assert num_to_chinese(None) == ""


# ---------------------------------------------------------------------------
# 逐位读（手机号 / 编号）
# ---------------------------------------------------------------------------
@pytest.mark.parametrize("text, expect", [
    ("2382", "二三八二"),
    ("13800138000", "一三八零零一三八零零零"),
    ("-3.5", "负三点五"),
    ("abc", ""),
])
def test_digits_to_chinese(text, expect):
    assert digits_to_chinese(text) == expect